bool1 = False
bool2 = True

print(f'The content of the variable is: {bool1, bool2}')

greaterThan = 1 > 2
print(f'1 is greater than 2: {greaterThan}')

lessThan = 1 < 2
print(f'1 is less than 2: {lessThan}')

greaterEqual = 1 >= 2
print(f'1 is greater than or equal to 2: {greaterEqual}')

lessEqual = 1 <= 2
print(f'1 is less than or equal to 2: {lessEqual}')

equalTo = 2 == 2
print(f'2 is equal to 2: {equalTo}')

notEqual = 2 != 2
print(f'2 is not equal/different to 2: {notEqual}')

convertedLogical = bool(0)
print(f'The value of 0 converted to logical value is: {convertedLogical}')

convertedLogical = bool(1)
print(f'The value of 1 converted to logical value is: {convertedLogical}')